def basic_info(canonical: Optional[str], test_name: str, language: str) -> str:
    entry = BASIC_INFO.get(canonical or "")
    if entry:
        if language == "hi":
            return entry.get("hi") or entry["en"]
        if language == "hinglish":
            return entry["en"]
        return entry["en"]
    if language == "hi":
        return f"यह जाँच {test_name} को मापती है। आपकी प्रयोगशाला रिपोर्ट ही बताती है कि यह क्या मापती है।"
    if language == "hinglish":
        return f"Yeh test {test_name} ko measure karta hai. Aapki lab report hi batati hai ki yeh kya measure karta hai."
    return (
        f"This test measures {test_name}. Your laboratory report is the best source "
        "for what it measures and why it was ordered."
    )


def _format_range(ctx: ResultContext, language: str) -> str:
    if not ctx.range_text:
        return LABELS[language]["range_missing"]
    unit = f" {ctx.range_unit}" if ctx.range_unit else ""
    return f"{ctx.range_text}{unit}"


def _value_repr(ctx: ResultContext) -> str:
    if ctx.value is not None:
        text = ctx.value_text or f"{ctx.value:g}"
        return f"{text} {ctx.unit}".strip()
    if ctx.value_text:
        return ctx.value_text
    return ""


def render_template(ctx: ResultContext, language: str) -> str:
    language = language if language in LABELS else "en"
    labels = LABELS[language]

    info = basic_info(ctx.canonical_name, ctx.test_name, language)
    value = _value_repr(ctx)
    status_label = labels.get(ctx.status, ctx.status)
    range_repr = _format_range(ctx, language)

    if ctx.status == STATUS_QUALITATIVE:
        summary = f"{ctx.test_name}: {value} — {status_label}."
    else:
        summary = (
            f"{ctx.test_name}: {value}; reference range: {range_repr} — {status_label}."
        )

    status_text = STATUS_TEXT[language].get(ctx.status, STATUS_TEXT[language][STATUS_UNKNOWN])
    context = CONTEXT_TEXT[language]
    if ctx.critical_flag:
        context = f"{context} {CRITICAL_TEXT[language]}"

    questions = QUESTIONS[language]
    question_block = "\n".join(f"- {question}" for question in questions)

    return (
        f"**{labels['what_is']}**\n{info}\n\n"
        f"**{labels['result']}**\n{summary} {status_text}\n\n"
        f"**{labels['else']}**\n{context}\n\n"
        f"**{labels['questions']}**\n{question_block}"
    )


